    std::vector<carGraph::CarRect> &carGraph::getCarGraph(carGraph::CarStatus s) {
        switch (s) {
            case NORMAL: return normal_graph;
                break;
            case RIGHT: return right_graph;
                break;
            case LEFT: return left_graph;
                break;
            default:
                break;
        }
    }

    void carGraph::render(float carX, float carY, float CELL, CarStatus status, SDL_Renderer* renderer) {
        for (const CarRect& p : getCarGraph(status)){
            SDL_FRect rc ={carX + p.x * CELL, carY + p.y * CELL, p.w * CELL, p.h * CELL};
            SDL_SetRenderDrawColor(renderer, p.r, p.g, p.b, 255);
            SDL_RenderFillRectF(renderer, &rc);
        }
    }

